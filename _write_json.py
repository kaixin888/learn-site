BASE = 'https://learn.clowand.com/api'
results = []
for i, card in enumerate(cards):
    data = json.dumps(card, ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(
        f'{BASE}/notes',
        data=data,
        headers={'Content-Type': 'application/json'},
        method='POST'
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            r = json.loads(resp.read().decode('utf-8'))
            results.append({'index': i, 'title': card['title'], 'slug': r.get('slug'), 'status': 'OK'})
            print(f"[{i}] OK  slug={r.get('slug')}  |  {card['title'][:40]}")
    except Exception as e:
        body = e.read().decode('utf-8') if hasattr(e, 'read') else ''
        results.append({'index': i, 'title': card['title'], 'status': f'ERR: {e} {body[:200]}'})
        print(f"[{i}] ERR  {e}  {body[:200]}")

print()
print(f"=== UPLOAD RESULTS: {sum(1 for r in results if r['status']=='OK')}/{len(cards)} ===")
